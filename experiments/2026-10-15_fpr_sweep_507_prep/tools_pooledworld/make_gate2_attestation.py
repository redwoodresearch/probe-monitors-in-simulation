"""PATH 1 gate-2 attestation NOTE for the pooled launch at the reviewed 9c pin (09 READ_LOG @ fd8acb838; 0d / 2e via 507-prep, 10-16 ~19:35 PT).
Keys, shas and positions only; generated by script. STOPs (exit 1, no NOTE) unless:
  - every top-level .py of the experiment folder (the module pin's universe: PW_CODE_MODULES and any other imported module of the folder) and
    run_peraction311.py have the same blob at HEAD as at the reviewed 9c commit (so script_sha256 and modules_sha256 are the reviewed ones);
  - PW_GATE2_DECLARED, read from the runner's source at HEAD, has member sets EXACTLY the 3 groups below;
  - E2E's check_token_prefix record at the pinned commit has the pinned sha256, its controls pass, and every key pair inside each declared group
    is one of its pairs with verdict "(1) natural" (positions d / max need read by key from its uncut line, printed beside).
usage: python3 make_gate2_attestation.py <out NOTE .md>"""
import ast
import hashlib
import itertools
import json
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

EXP = Path(__file__).resolve().parents[1]
REL = "experiments/2026-10-15_fpr_sweep_507_prep"
PIN_9C = "df8e616cd"
RECORD = ("571883e36", "experiments/2026-10-15_e2e_sim_pipeline/results/check_token_prefix_2026-10-16_192643.json",
          "c7b0da2f42cfece95ce1675983173d2c6383c80c92325d152fa10e0dbe06f7a6")
GROUPS = {frozenset(("honest_a_e2|nm172_shared_dotfiles", "simh_nm360|nm172_shared_dotfiles")),
          frozenset(("honest_a_e2|nm305_user_tracking", "honest_b_e2|nm305_user_tracking", "honest_b|nm305_user_tracking")),
          frozenset(("honest_a_e2|nm305_user_tracking", "honest_b_e2|nm305_user_tracking"))}
VERBATIM = ["09 verified the 571883e36 verdicts and controls by key at 10-16 19:33 PDT (READ_LOG @ fd8acb838)",
            "0d recheck: pending → gates release",
            "same scoring model: PENDING (b), fails closed at release"]
HELD = "HELD: release gated on (b) scorer weights, the e2-copy census, 0d's recheck of 571883e36"


def git(*a):
    return subprocess.run(["git", *a], capture_output=True, check=True, cwd=EXP).stdout


def stop(msg):
    print(f"STOP: {msg}")
    sys.exit(1)


out = Path(sys.argv[1])
head = git("rev-parse", "HEAD").decode().strip()
if git("status", "--porcelain", "--untracked-files=no", "--", ".").strip():
    stop("uncommitted tracked changes in the experiment folder")
blobs = {}
for c in (PIN_9C, head):
    ls = git("ls-tree", "--full-tree", c, f"{REL}/").decode().splitlines()
    blobs[c] = {ln.split("\t")[1].rsplit("/", 1)[1]: ln.split()[2] for ln in ls if ln.endswith(".py")}
if not blobs[head] or "run_peraction311.py" not in blobs[head]:
    stop("no top-level .py modules found at HEAD (ls-tree)")
if blobs[PIN_9C] != blobs[head]:
    stop(f"top-level .py blobs differ between {PIN_9C} and HEAD: {sorted(k for k in set(blobs[PIN_9C]) | set(blobs[head]) if blobs[PIN_9C].get(k) != blobs[head].get(k))}")
src = git("show", f"{head}:{REL}/run_peraction311.py")
sha = lambda b: hashlib.sha256(b).hexdigest()  # noqa: E731
script_sha = {c: sha(git("show", f"{c}:{REL}/run_peraction311.py")) for c in (PIN_9C, head)}
mods = {c: {n: sha(git("show", f"{c}:{REL}/{n}")) for n in sorted(blobs[c])} for c in (PIN_9C, head)}
mods_sha = {c: sha(json.dumps(mods[c], sort_keys=True).encode()) for c in (PIN_9C, head)}
decl = None
for node in ast.parse(src).body:
    if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "PW_GATE2_DECLARED" for t in node.targets):
        decl = {frozenset(ast.literal_eval(e.args[0])) for e in node.value.elts}
        line = node.lineno
if decl != GROUPS:
    stop(f"PW_GATE2_DECLARED at HEAD is not exactly the 3 groups: {sorted(sorted(g) for g in (decl or set()))}")
rb = git("show", f"{RECORD[0]}:{RECORD[1]}")
if sha(rb) != RECORD[2]:
    stop("check_token_prefix record sha256 differs from the pin")
R = json.loads(rb)
if (R.get("controls") or {}).get("pass") is not True:
    stop("the record's controls do not pass")
pairs = {frozenset(p["pair"]): p for p in R["pairs"]}
cov = []
for g in sorted(GROUPS, key=sorted):
    for a, b in itertools.combinations(sorted(g), 2):
        p = pairs.get(frozenset((a, b)))
        if p is None or not p["verdict"].startswith("(1) natural"):
            stop(f"group {sorted(g)}: pair {a} / {b} is not a natural pair of the record")
        u = p["lines"].get("uncut") or {}
        fs = u.get("files") or []
        idn = [f for f in fs if f.get("observed_identical")]
        bad = [f["file_x"] for f in idn if f.get("outcome") != "natural" or not f.get("routing_equal")]
        if not idn or bad:
            stop(f"group {sorted(g)}: pair {a} / {b}: uncut identical files missing or not natural with equal routing: {bad[:3]}")
        cov.append({"group": sorted(g), "pair": [a, b], "verdict": p["verdict"], "uncut_common_prefix": u.get("common_prefix"),
                    "uncut_identical_files": len(idn), "uncut_max_need": max(max(x for x in f["max_need"] if x is not None) for f in idn)})
made = datetime.now(ZoneInfo("America/Los_Angeles")).strftime("%Y-%m-%d %H:%M:%S %Z")
L = [f"# Gate-2 attestation NOTE (PATH 1), pooled launch at the reviewed 9c pin: generated by {Path(__file__).name} at {made}", "",
     HELD, "", *VERBATIM, "",
     f"- launch commit (HEAD): {head}; reviewed 9c pin: {PIN_9C}",
     f"- script_sha256 (run_peraction311.py): 9c {script_sha[PIN_9C]} | HEAD {script_sha[head]} | equal: {script_sha[PIN_9C] == script_sha[head]}",
     f"- top-level .py modules (sha256 of the per-file sha256 map, {len(mods[head])} files): 9c {mods_sha[PIN_9C]} | HEAD {mods_sha[head]} | equal: "
     f"{mods_sha[PIN_9C] == mods_sha[head]}",
     f"- PW_GATE2_DECLARED (run_peraction311.py:{line} at HEAD), asserted equal to the 3 groups: {json.dumps(sorted(sorted(g) for g in decl))}",
     f"- record: {RECORD[0]}:{RECORD[1]} @ sha256 {RECORD[2]} (verified); controls.pass: true",
     "- declared-group pairs in the record (keys; uncut line positions):"]
L += [f"  - {json.dumps(c)}" for c in cov]
L += ["- 09 READ_LOG (experiments/2026-10-14_priority1_spec_09/READ_LOG.md): 7539a8596 (hold lifted), f9beab2b3 (launch list), fd8acb838 (PATH 1: "
      "launch at the current pin with this NOTE; 09 verified 571883e36 by key), a79650178 (pilot now, A after the pilot and (b))",
      "- undeclared groups still STOP in-run (pw_union gate 2 at the pin); the E12-pair exemption is unchanged at the pin"]
out.write_text("\n".join(L) + "\n")
print("\n".join(L))
