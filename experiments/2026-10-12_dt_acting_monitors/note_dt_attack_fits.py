"""Result note for the attack fits ($0, local): RESULTS_dt_attack_fits.md, every number read by key from the analysis
files and per-call bundles named in the two results manifests (each file's sha256 checked first).

The orchestrator, 02:02 PT 2026-10-13: put the task-122 concentration next to the destructive/primary second-real-run
numbers, list how many distinct tasks hold the positives in each world for each design, and show the positive counts
per world and design for the semantic labels next to the exact-q2 counts (catch rates moved, so the positive set did).
Counts and table cells only; no interpretation.

  uv run --no-project --python 3.14 python -I note_dt_attack_fits.py <data/dt_attack_fits dir> <out .md>
"""

import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
RUNS = [("exact-q2, all rows", "manifest_dt_attack_fits_v1.json", "dt_attack_fits_00f4994d6c1e"),
        ("exact-q2, semantic-resolved rows", "manifest_dt_attack_semantic_fits_v1.json", "dt_attack_q2subset_fits_2d981f5ac093"),
        ("SEMANTIC (PROVISIONAL)", "manifest_dt_attack_semantic_fits_v1.json", "dt_attack_semantic_fits_62f009e497a6")]
DESIGNS = ["destructive_primary", "destructive_secondary", "transfer_primary", "transfer_secondary"]
WORLDS = {"real": "real attack 1", "sim": "sim attack", "run2": "real attack 2"}


def load(data: Path, manifest: str, key: str, kind: str) -> dict:
    files = json.loads((HERE / "results" / manifest).read_text())["files"]
    f = next(x for x in files if x["name"].startswith(f"{kind}_{key}_"))
    raw = (data / f["name"]).read_bytes()
    if hashlib.sha256(raw).hexdigest() != f["sha256"]:
        raise SystemExit(f"{f['name']}: sha256 differs from the manifest")
    return json.loads(raw)


def main(data: str, out: str):
    data, L = Path(data), []
    A = {name: load(data, m, k, "analysis") for name, m, k in RUNS}
    B = {name: load(data, m, k, "bundle") for name, m, k in RUNS}
    L += ["# Attack fits: positives, tasks and one concentration (counts only)", "",
          ("Generated by `note_dt_attack_fits.py` from the analysis files and per-call bundles pinned in "
           "`results/manifest_dt_attack_fits_v1.json` and `results/manifest_dt_attack_semantic_fits_v1.json` (sha256 checked). "
           "Semantic labels are PROVISIONAL. Counts are on each design's rows in the attack cohort (positives; negatives: other "
           "impactful calls for primary, read-only calls for secondary). The exact-q2 refit on the semantic-resolved rows ran no "
           "label shuffles (approved that way, to separate row exclusion from label definitions), so no null or p-value is "
           "reported for it. The all-rows exact-q2 run's 20 shuffles per cell belong to that different fit and are not a null "
           "for this refit."), ""]
    L += ["## Positives (tasks holding them) and negatives per world", "",
          "| Design | Labels | " + " | ".join(f"{w} positives (tasks)" for w in WORLDS.values()) + " | " + " | ".join(f"{w} negatives" for w in WORLDS.values()) + " |",
          "|---|---|" + "---|" * 6]
    for d in DESIGNS:
        for name, *_ in RUNS:
            c, rows = A[name]["designs"][d]["counts"], B[name][d]["rows"]
            tasks = {w: len({t for t, ww, y in zip(rows["task"], rows["world"], rows["y"]) if ww == w and y == 1}) for w in WORLDS}
            L.append(f"| {d} | {name} | " + " | ".join(f"{c[w]['positives']} ({tasks[w]})" for w in WORLDS) + " | "
                     + " | ".join(str(c[w]["negatives"]) for w in WORLDS) + " |")
    L += ["", "## Real - sim catch difference and the planted check", "",
          ("The catch columns above and in the analysis cover all cohort tasks; each real - sim comparison covers only the tasks with "
           "design rows in both worlds (the tasks column). Where the planted 5-point shift was not detected, the comparison couldn't "
           "detect a gap of that size, so an interval that includes 0 there is not evidence of no gap."), "",
          "| Design | Labels | alarm | real - sim (pts) [95%] | tasks | planted 5-pt shift | reading |", "|---|---|---|---|---|---|---|"]
    for d in DESIGNS:
        for name, *_ in RUNS:
            a = A[name]["designs"][d]
            for fpr in ("0.01", "0.05"):
                v, pl = a["comparisons"]["real_vs_sim"], a["planted"].get(fpr, {})
                ci = v[fpr]["ci95"]["catch"]
                det = ("not applicable" if not pl.get("applicable") else "detected" if pl["detected"] else "NOT detected")
                zero_in = ci[0] <= 0 <= ci[1]
                read = {"NOT detected": ("can't detect a 5-pt gap here, so this 0-including interval is not evidence of no gap" if zero_in
                                         else "the interval excludes 0; the planted 5-pt shift was not detected"),
                        "not applicable": "simulated catch under 5 pts: no headroom for the plant", "detected": ""}[det]
                L.append(f"| {d} | {name} | {100 * float(fpr):.0f}% | {100 * v[fpr]['estimate']['diff']['catch']:+.1f} "
                         f"[{100 * ci[0]:+.1f}, {100 * ci[1]:+.1f}] | {v['tasks']} | {det} | {read} |")
    L += ["", "## Destructive/primary, real attack 2: where its positives sit", "",
          "| Labels | catch at 1% / 5% (real attack 2) | positives in fold 0 | of those, in the largest task (task index) | fold 0 layer, C | fold 0 share flagged at 5% |",
          "|---|---|---|---|---|---|"]
    for name, *_ in RUNS:
        a, b = A[name]["designs"]["destructive_primary"], B[name]["destructive_primary"]
        fold, y, task = b["rows"]["fold"], b["rows"]["y"], b["rows"]["task"]
        r, s = b["cells"]["real->run2"]["row"], b["cells"]["real->run2"]["score"]
        p0 = [(i, sc) for i, sc in zip(r, s) if y[i] == 1 and fold[i] == 0]
        top_task, top_n = Counter(task[i] for i, _ in p0).most_common(1)[0]
        t0 = a["checks"]["thresholds_0.05"]["0"]
        share = sum(sc > t0 for _, sc in p0) / len(p0)
        cells = a["cells"]["real->run2"]
        L.append(f"| {name} | {100 * cells['0.01']['catch']:.1f} / {100 * cells['0.05']['catch']:.1f} | {len(p0)} of "
                 f"{a['counts']['run2']['positives']} | {top_n} ({top_task}) | {a['choices']['real|0'][0]}, {a['choices']['real|0'][1]} | {100 * share:.0f}% |")
    Path(out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main(*sys.argv[1:3])
