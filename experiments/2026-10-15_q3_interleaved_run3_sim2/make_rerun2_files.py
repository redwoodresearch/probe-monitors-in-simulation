"""Second paired rate-limit reruns for s1 and s2 (0d 03:52 GO; 09 registers): il_s1_rlr and il_s2_rlr admitted nothing
(caps $61 / $41 are below the launcher's ~$75 per-sim admission reserve; il_s2_rlr ended 03:21:28 with all 4 runs
"not run: spend cap", il_s1_rlr was never started). Same cells, same task files (config/tasks_ilrr_<h>.json) and the same
pinned failed-original bindings (config/ilrr_rerun_of_<h>.json, both @ f368ebab); only the cap changes:
cap = round(cells x price + min(cells, 5) x $75) (s1 3 cells $269, s2 2 cells $179). Addendum (0d 04:08): q4's paired rerun
(registered at $225, never started) runs as q4_rlr2 on box 1 with the same rule: 11 x $14.61 + 5 x $75 = $536.
Writes config/pilot_ilrr2_<h>.yaml and ilrr2_box.sh (ilrr_box.sh @ the given commit with mechanical renames: run dir
2026-10-15_il_<h>_rlr2, session ilrlr2<h>, config pilot_ilrr2_<h>.yaml, its own original-pairs and settings files; the
case table holds s1 and s2 only). Never overwrites.
  python3 make_rerun2_files.py <commit with ilrr_box.sh>
"""

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
C = HERE / "config"
PRICE, RESERVE = 14.6079, 75.0
EXTRA_C = " ! -path './config/pilot_ilc_*' ! -path './config/tasks_ilc_*' ! -path './config/ilc_*'"
RNM = "/home/aswin/phase2/nm/runs"
R311 = "/home/aswin/phase2/runs"
PREVS = {"s1": [f"{RNM}/2026-10-14_il_s1", f"{RNM}/2026-10-14_il_s4d"],  # il_s1_rlr never started (its starter was stopped)
         "s2": [f"{RNM}/2026-10-14_il_s2", f"{RNM}/2026-10-15_il_s2_rlr"],
         "q4b1": [f"{R311}/2026-10-14_il_q4", f"{R311}/2026-10-14_il_q1", f"{R311}/2026-10-15_il_q1_rlr"]}  # q4_rlr never started
HF = {"s1": "s1", "s2": "s2", "q4b1": "q4"}
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()  # noqa: E731


def main() -> None:
    commit = subprocess.check_output(["git", "rev-parse", f"{sys.argv[1]}^{{commit}}"], text=True).strip()
    box = subprocess.check_output(["git", "show", f"{commit}:experiments/2026-10-15_q3_interleaved_run3_sim2/ilrr_box.sh"], text=True)
    cases = {}
    for key in PREVS:
        h = HF[key]
        line = next(x for x in box.splitlines() if x.startswith(f"  {key}) "))
        cells = json.loads((C / f"tasks_ilrr_{h}.json").read_text())["cells"]
        cap = round(len(cells) * PRICE + min(len(cells), 5) * RESERVE)
        text = (C / f"pilot_ilrr_{h}.yaml").read_text()
        note = (f"{len(cells)} cells x (${PRICE} + ${RESERVE:.0f} admission reserve)" if len(cells) <= 5 else  # s1/s2 text @ e46ba05d0
                f"{len(cells)} cells x ${PRICE} + 5 x ${RESERVE:.0f} admission reserve")
        text, n1 = re.subn(r"(?m)^  cap_usd: .*$", f"  cap_usd: {cap}   # {note}", text)
        text, n2 = re.subn(r"(?m)^  worst_case_limit_usd: .*$", f"  worst_case_limit_usd: {cap}   # = cap", text)
        assert n1 == n2 == 1, h
        out = C / f"pilot_ilrr2_{h}.yaml"
        if out.exists() and key != "q4b1":  # s1/s2 @ e46ba05d0: must regenerate byte-identically
            old = out.read_bytes()
            out.unlink()
        else:
            old = None
            assert not out.exists(), out
        out.write_text(f"# SECOND PAIRED RATE-LIMIT RERUN {h} (rlr2): pilot_ilrr_{h}.yaml with only the cap changed (admission).\n" + text)
        assert old is None or out.read_bytes() == old, f"{out} changed"
        new = re.sub(r"CAP=\d+;", f"CAP={cap};", line)
        new = re.sub(r"CSHA=[0-9a-f]{64};", f"CSHA={sha(out)};", new)
        new = re.sub(r'PREVS="[^"]*";', f'PREVS="{" ".join(PREVS[key])}";', new)
        assert new.count(f"CAP={cap};") == 1 and new.count(sha(out)) == 1, h
        cases[key] = new
    i0, i1 = box.index("case $H in\n") + len("case $H in\n"), box.index("  *) echo \"host $H: no rerun prepared\"")
    box = box[:i0] + "\n".join(cases[k] for k in PREVS) + "\n" + box[i1:]
    for a, b, n in [
        ("# GENERATED by make_rerun_files.py (the case table); do not edit by hand.",
         f"# rlr2 (make_rerun2_files.py from ilrr_box.sh @ {commit[:12]}): the s1/s2 reruns again, and q4's rerun, with caps that admit cells;\n"
         "# mechanical renames only (run dir _rlr2, session ilrlr2, config pilot_ilrr2_, original-pairs and settings files). Do not edit.", 1),
        ("RUN=/home/aswin/phase2/runs/2026-10-15_il_${HF}_rlr;", "RUN=/home/aswin/phase2/runs/2026-10-15_il_${HF}_rlr2;", 1),
        ("RUN=/home/aswin/phase2/nm/runs/2026-10-15_il_${HF}_rlr;", "RUN=/home/aswin/phase2/nm/runs/2026-10-15_il_${HF}_rlr2;", 1),
        ("SESSION=ilrlr$HF; LOG=/home/aswin/phase2/il_${HF}_rlr.log;", "SESSION=ilrlr2$HF; LOG=/home/aswin/phase2/il_${HF}_rlr2.log;", 1),
        ("config/pilot_ilrr_$HF.yaml", "config/pilot_ilrr2_$HF.yaml", 2),
        ('"$ST/pilot_ilrr_$HF.yaml"', '"$ST/pilot_ilrr2_$HF.yaml"', 1),
        ("[il ${HF}_rlr @ $H]", "[il ${HF}_rlr2 @ $H]", 1),
        ("#   bash ~/phase2/il_stage/ilrr_box.sh <host>", "#   bash ~/phase2/il_stage/ilrr2_box.sh <host>", 1),  # Codex r20 nit
        ('open(f"config/pilot_ilrr_{h}.yaml")', 'open(f"config/pilot_ilrr2_{h}.yaml")', 1),
        ('results/ilrr_original_pairs_{h}.json', 'results/ilrr2_original_pairs_{h}.json', 1),
        ('"$SRC/results/ilrr_original_pairs_$HF.json"', '"$SRC/results/ilrr2_original_pairs_$HF.json"', 1),
        ('GS="results/gate_settings_ilrr_${HF}_', 'GS="results/gate_settings_ilrr2_${HF}_', 1),
        ("\"launch\": \"il_%s_rlr\"", "\"launch\": \"il_%s_rlr2\"", 1),
        ("! -path './config/pilot_ilrr_*'", "! -path './config/pilot_ilrr_*' ! -path './config/pilot_ilrr2_*' ! -path './config/pilot_ilrr3_*'"
         " ! -path './config/tasks_ilrr3_*' ! -path './config/ilrr3_*'" + EXTRA_C, 1),  # every registered order on a box (Codex r21)
    ]:
        assert box.count(a) == n, (a, box.count(a))
        box = box.replace(a, b)
    assert "_rlr;" not in box and "_rlr.log" not in box, "an unrenamed run path"
    out = HERE / "ilrr2_box.sh"
    if out.exists():
        out.unlink()  # regenerated with the q4b1 case added (addendum); s1/s2 case lines are unchanged
    out.write_text(box)
    print(json.dumps({k: {"cap": int(re.search(r"CAP=(\d+);", cases[k]).group(1)), "config_sha256": sha(C / f"pilot_ilrr2_{HF[k]}.yaml")} for k in cases}))


if __name__ == "__main__":
    main()
