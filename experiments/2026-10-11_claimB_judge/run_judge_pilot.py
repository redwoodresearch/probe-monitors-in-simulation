"""AI-judge dev pilot (PLAN.md amendment 1): a plumbing test. Three judges score seeded dev runs, planted copies and a
retest subset. Gives NO AUROC reading. API spend from the laptop: OpenAI direct (GPT-5.6 Sol, GPT-6 Astra) and
OpenRouter (Claude Fable 5.1); keys from ~/probe-distribution-shift-from-sims/.env, loaded into this process only, never
printed, logged or written.

Only keys and numbers leave this process: one record per request in results/judge_pilot_calls.jsonl (append-only, one
file across resumed runs): judge, model, provider, params, git, cell, arm, kind, position, replicate, status, parsed p,
tokens, cost, cached. Raw judge responses go to a cache outside git (JUDGE_CACHE, checked to lie outside the repo),
keyed by sha256 of prompt + model + params + replicate, written atomically, never printed; a rerun resumes from it.
Budget: every request reserves its worst-case cost under a lock before it is sent, against $125 minus all spend billed
so far (a ledger beside the cache survives restarts). Any safety filter or provider refusal stops the whole job, is
persisted (STOP file) so a restart won't launch, and is checked before every attempt. Parse failures and other API
errors are counted and redrawn once (redraws above 10% stop the job); none is ever scored. The first 6 calls (2 per
judge) must each cost at most 1.5x the upper estimate, and at least one per judge must parse, before the rest launch.

  uv run --no-project --python 3.12 --with 'modal>=1.4.3' --with httpx \\
      python experiments/2026-10-11_claimB_judge/run_judge_pilot.py
"""

