def worst_cost(judge, text):
    """An upper bound on one attempt's cost: byte-level tokens cover at least one byte, so input tokens <= UTF-8 bytes,
    plus 2,000 tokens of framing."""
    rin, rout = JUDGES[judge]["rates"]
    return ((len(text.encode()) + len(PROMPT.encode()) + 2000) * rin + MAX_OUT * rout) / 1e6


def num(x) -> float:
    return float(x) if isinstance(x, (int, float)) and not isinstance(x, bool) else 0.0


def billed(judge, text, u) -> float:
    """Cost from a usage block (provider cost if given); a missing or malformed block is charged the worst case."""
    if not isinstance(u, dict) or not u:
        return worst_cost(judge, text)
    if u.get("cost") is not None and num(u.get("cost")) > 0:
        return num(u.get("cost"))
    rin, rout = JUDGES[judge]["rates"]
    tin = u.get("input_tokens", u.get("prompt_tokens"))
    tout = u.get("output_tokens", u.get("completion_tokens"))
    valid = all(isinstance(x, (int, float)) and not isinstance(x, bool) and x >= 0 for x in (tin, tout))
    return (tin * rin + tout * rout) / 1e6 if valid else worst_cost(judge, text)  # partial usage: worst case


def load_runs():
    """Dev runs of the three arms from the level-1 staging (messages in memory only) and their pack positions."""
    vol = modal.Volume.from_name(VOL, version=2)
    pack = {(r["cell"], r["arm"]): r for r in json.loads(b"".join(vol.read_file(f"{PACK}/runs.L19.json"))) if r["environment"] in DEV}
    runs = {}
    for path in sorted(e.path for e in vol.listdir(f"{STAGED}/inputs")):
        for line in b"".join(vol.read_file(path)).splitlines():
            r = json.loads(line)
            if r["environment"] in DEV and r["arm"] in (SIM, E1, E2):
                if (r["cell"], r["arm"]) in pack and pack[(r["cell"], r["arm"])]["key"] != r["key"]:
                    raise SystemExit("staging and pack disagree on a run key")
                runs[(r["cell"], r["arm"])] = r["messages"]
    return runs, pack


def indices(msgs):
    """The reader's counting: (step -> assistant message index, (step, action) -> tool message index)."""
    step, action, a_idx, t_idx = -1, 0, {}, {}
    for i, m in enumerate(msgs):
        if m["role"] == "assistant":
            step, action = step + 1, 0
            a_idx[step] = i
        elif m["role"] == "tool":
            t_idx[(step, action)] = i
            action += 1
    return a_idx, t_idx


def cut(msgs, positions):
    """(messages through the segment of the run's last kept position, tool-message indices of kept outputs)."""
    a_idx, t_idx = indices(msgs)
    kept_out = sorted(t_idx[(p["step"], p["action"])] for p in positions if p["kind"] == "output_end" and p["kept"] and p.get("token") is not None)
    with_tok = [p for p in positions if p.get("token") is not None]
    if all(p["kept"] for p in with_tok):
        return list(msgs), kept_out
    last = max((p for p in with_tok if p["kept"]), key=lambda p: p["token"])
    end = t_idx[(last["step"], last["action"])] if last["kind"].startswith("output") else a_idx[last["step"]]
    return list(msgs[: end + 1]), [i for i in kept_out if i <= end]


def text_of(x):
    return x if isinstance(x, str) else json.dumps(x, ensure_ascii=False)


def render(msgs):
    parts = []
    for m in msgs:
        if m["role"] in ("system", "user"):
            parts.append(f"=== {m['role'].upper()} ===\n" + scrub(text_of(m.get("content") or ""), 1))
        elif m["role"] == "assistant":
            t = "=== AGENT ===\n" + scrub(text_of(m.get("content") or ""), 1)
            for c in m.get("tool_calls") or []:
                fn = c["function"]
                t += f"\n[tool call] {fn['name']} " + scrub(text_of(fn.get("arguments") or ""), 1)
            parts.append(t)
        elif m["role"] == "tool":
            parts.append(f"=== TOOL OUTPUT ({m.get('tool_name') or 'tool'}) ===\n" + scrub(text_of(m.get("content") or ""), 1))
    return "\n\n".join(parts)


def plant(msgs, kept_out, where):
    """The notice appended to the kept output nearest `where` of the way through the run's kept outputs."""
    i = kept_out[round(where * (len(kept_out) - 1))]
    out = [dict(m) for m in msgs]
    out[i] = out[i] | {"content": text_of(out[i].get("content") or "") + "\n" + PLANT}
    return out


def jobs_for(runs, pack):
    cells = sorted(c for c in {c for c, _ in runs} if all((c, a) in runs and (c, a) in pack for a in (SIM, E1, E2)))
    pick = random.Random("judge-pilot").sample(cells, N_CELLS)
    sims, reals = random.Random("judge-pilot-plant-sim").sample(pick, N_PLANT), random.Random("judge-pilot-plant-real").sample(pick, N_PLANT)
    base = [(c, a) for c in pick for a in (SIM, E1, E2)]
    retest = random.Random("judge-pilot-retest").sample(base, N_RETEST)
    cutm = {k: cut(runs[k], pack[k]["positions"]) for k in base}
    jobs = [{"cell": c, "arm": a, "kind": "main", "position": None, "replicate": "0", "text": render(cutm[(c, a)][0])} for c, a in base]
    for arm, chosen in ((SIM, sims), (E1, reals)):
        for c in chosen:
            msgs, kept_out = cutm[(c, arm)]
            if not kept_out:
                raise SystemExit("a planted run has no kept output")
            for pos, w in POSITIONS.items():
                jobs.append({"cell": c, "arm": arm, "kind": "plant", "position": pos, "replicate": "0", "text": render(plant(msgs, kept_out, w))})
    jobs += [{"cell": c, "arm": a, "kind": "retest", "position": None, "replicate": "1", "text": render(cutm[(c, a)][0])} for c, a in retest]
    sel = {"cells": pick, "plant_sim": sims, "plant_real": reals, "retest": [list(x) for x in retest],
           "expected_jobs": [{k: j[k] for k in ("cell", "arm", "kind", "position", "replicate")} for j in jobs]}
    return jobs, sel


def parse(text):
    """p from a reply that is exactly a JSON object {"p_simulated": number in [0, 1]} (code fences allowed), else None."""
    if not isinstance(text, str):
        return None
    t = text.strip()
    t = re.sub(r"^```(?:json)?\s*|\s*```$", "", t).strip()
    try:
        obj = json.loads(t)
    except ValueError:
        return None
    if not isinstance(obj, dict) or set(obj) != {"p_simulated"}:
        return None
    p = obj["p_simulated"]
    return float(p) if isinstance(p, (int, float)) and not isinstance(p, bool) and 0.0 <= p <= 1.0 else None


def safety(err) -> bool:
    """A safety filter or refusal, from an error's code, type, metadata or message (searched, never stored or printed)."""
    if not err:
        return False
    fields = {k: err.get(k) for k in ("code", "type", "metadata", "message")} if isinstance(err, dict) else {"err": err}
    return bool(SAFETY.search(json.dumps(fields, default=str)))


async def call(client, judge, text, keys, state):
    """(status, p, usage, cost, raw). status: ok | parse_failure | refusal | api_error:<what>. Raw goes to the cache only.
    cost covers every attempt: a timed-out attempt is charged its worst case, since the server may have billed it."""
    j = JUDGES[judge]
    status, raw, spent = "api_error:not_sent", None, 0.0
    for attempt in range(2):  # one retry, for transient 429/5xx or a timeout only; never a redraw
        if state["stop"]:
            return "api_error:stopped", None, {}, spent, None
        try:
            if j["provider"] == "openai":
                r = await client.post("https://api.openai.com/v1/responses", headers={"Authorization": f"Bearer {keys['OPENAI_API_KEY']}"},
                                      json={"model": j["model"], "instructions": PROMPT, "input": text, "reasoning": {"effort": "high"},
                                            "max_output_tokens": MAX_OUT})
            else:
                r = await client.post("https://openrouter.ai/api/v1/chat/completions", headers={"Authorization": f"Bearer {keys['OPENROUTER_API_KEY']}"},
                                      json={"model": j["model"], "messages": [{"role": "system", "content": PROMPT}, {"role": "user", "content": text}],
                                            "reasoning": {"effort": "high"}, "max_tokens": MAX_OUT, "usage": {"include": True}})
        except Exception as e:  # noqa: BLE001  (the type only; a message could echo request details)
            status, raw = f"api_error:{type(e).__name__}", None
            spent += worst_cost(judge, text)
            await asyncio.sleep(5 * (attempt + 1))
            continue
        try:
            raw = r.json()
        except ValueError:
            raw = None
        if not isinstance(raw, dict):
            raw = {"non_dict_body_status": r.status_code}
        err = raw.get("error")
        if r.status_code >= 500:  # the server may have generated before failing: usage if given, else the worst case
            spent += billed(judge, text, raw.get("usage"))
        elif r.status_code != 200 and raw.get("usage"):  # any other error that still reports usage is still billed
            spent += billed(judge, text, raw.get("usage"))
        if r.status_code == 403 or safety(err):  # safety first, before any retry
            return "refusal", None, {}, spent, raw
        if r.status_code in (429, 500, 502, 503, 504):
            status = f"api_error:{r.status_code}"
            await asyncio.sleep(10 * (attempt + 1))
            continue
        break
    else:
        return status, None, {}, spent, raw
    if r.status_code != 200:
        return f"api_error:http_{r.status_code}", None, {}, spent, raw
    if err:  # a 200 carrying an error is billed from its usage, or the worst case
        return "api_error:error_in_body", None, {}, spent + billed(judge, text, raw.get("usage")), raw
    if j["provider"] == "openai":
        u = raw.get("usage") if isinstance(raw.get("usage"), dict) else {}
        det = u.get("output_tokens_details") if isinstance(u.get("output_tokens_details"), dict) else {}
        usage = {"input": num(u.get("input_tokens")), "output": num(u.get("output_tokens")), "reasoning": num(det.get("reasoning_tokens"))}
        cost = spent + billed(judge, text, u)
        items = [c for o in raw.get("output") or [] if isinstance(o, dict) and o.get("type") == "message" for c in o.get("content") or [] if isinstance(c, dict)]
        if any(c.get("type") == "refusal" for c in items) or (raw.get("incomplete_details") or {}).get("reason") == "content_filter":
            return "refusal", None, usage, cost, raw
        if raw.get("status") != "completed":
            return "api_error:incomplete", None, usage, cost, raw
        text_out = "".join(c["text"] for c in items if c.get("type") == "output_text" and isinstance(c.get("text"), str))
    else:
        u = raw.get("usage") if isinstance(raw.get("usage"), dict) else {}
        det = u.get("completion_tokens_details") if isinstance(u.get("completion_tokens_details"), dict) else {}
        usage = {"input": num(u.get("prompt_tokens")), "output": num(u.get("completion_tokens")), "reasoning": num(det.get("reasoning_tokens"))}
        cost = spent + billed(judge, text, u)
        ch = (raw.get("choices") or [{}])[0]
        ch = ch if isinstance(ch, dict) else {}
        msg = ch.get("message") if isinstance(ch.get("message"), dict) else {}
        if ch.get("finish_reason") == "content_filter" or ch.get("native_finish_reason") == "refusal" or msg.get("refusal") or safety(ch.get("error")):
            return "refusal", None, usage, cost, raw
        if ch.get("error") or ch.get("finish_reason") not in ("stop", "end_turn"):
            return "api_error:unfinished", None, usage, cost, raw
        text_out = msg.get("content") or ""
    p = parse(text_out)
    return ("ok" if p is not None else "parse_failure"), p, usage, cost, raw


def write_atomic(path: Path, data: str):
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(data)
    tmp.replace(path)


async def main():
    if subprocess.run(["git", "status", "--porcelain", str(Path(__file__))], capture_output=True, text=True, check=True).stdout:
        raise SystemExit(f"commit {Path(__file__).name} first")
    top = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True, cwd=HERE).stdout.strip()).resolve()
    if CACHE == top or top in CACHE.parents:
        raise SystemExit("the cache must lie outside the repo")
    git = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True, cwd=HERE).stdout.strip()
    CACHE.mkdir(parents=True, exist_ok=True)
    stop_file, ledger = CACHE / "STOP", CACHE / "spend.json"
    if stop_file.exists():
        raise SystemExit("a previous run stopped this job (STOP file in the cache); report before relaunching")
    keys = {}
    for line in ENV.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            if k.strip() in ("OPENAI_API_KEY", "OPENROUTER_API_KEY"):
                keys[k.strip()] = v.strip().strip('"').strip("'")
    runs, pack = load_runs()
    jobs, sel = jobs_for(runs, pack)
    del runs
    if SEL.exists() and json.loads(SEL.read_text())["expected_jobs"] != sel["expected_jobs"]:
        raise SystemExit("the selection differs from the one already started")
    (HERE / "results").mkdir(exist_ok=True)
    SEL.write_text(json.dumps(sel | {"git_first_launch": json.loads(SEL.read_text())["git_first_launch"] if SEL.exists() else git}, indent=1))
    led = json.loads(ledger.read_text()) if ledger.exists() else {"spent": 0.0, "pending": {}}
    # a reservation left pending by a crash may have been billed: count it as spent (over-counts, never under-counts)
    state = {"spent": led["spent"] + sum(led.get("pending", {}).values()), "pending": {}, "reserved": 0.0, "stop": None, "n": 0, "redraws": 0}
    write_atomic(ledger, json.dumps({"spent": state["spent"], "pending": {}}))
    sem, lock, key_locks = asyncio.Semaphore(CONC), asyncio.Lock(), {}

    async def one(client, judge, job, tag):
        key = hashlib.sha256(json.dumps({"provider": JUDGES[judge]["provider"], "model": JUDGES[judge]["model"], "params": PARAMS,
                                          "instructions": PROMPT, "input": job["text"], "replicate": tag}, sort_keys=True).encode()).hexdigest()
        async with key_locks.setdefault(key, asyncio.Lock()):
            cf = CACHE / f"{key}.json"
            if cf.exists():
                c = json.loads(cf.read_text())
                status, p, usage, cost, latency, cached = c["status"], c["p"], c["usage"], c["cost"], c["latency"], True
            else:
                worst = 2 * worst_cost(judge, job["text"])  # two attempts at most
                async with sem:  # reserve only once a slot is free, so queued jobs hold no reservation
                    async with lock:
                        if state["stop"] or state["spent"] + state["reserved"] + worst > STOP_USD:
                            state["stop"] = state["stop"] or "cost_stop"
                            return None
                        state["reserved"] += worst
                        state["pending"][key] = worst
                        write_atomic(ledger, json.dumps({"spent": state["spent"], "pending": state["pending"]}))  # persisted before sending
                    try:
                        t0 = time.time()
                        status, p, usage, cost, raw = await call(client, judge, job["text"], keys, state)
                        latency, cached = time.time() - t0, False
                        async with lock:  # the ledger first: a crash after this re-sends (over-counts), never under-counts
                            state["spent"] += cost
                            state["pending"].pop(key, None)
                            write_atomic(ledger, json.dumps({"spent": state["spent"], "pending": state["pending"]}))
                    finally:
                        async with lock:
                            state["reserved"] -= worst
                if status == "api_error:stopped":
                    return None
                write_atomic(cf, json.dumps({"status": status, "p": p, "usage": usage, "cost": cost, "latency": latency, "raw": raw}))
        async with lock:
            state["n"] += 1
            rec = {"judge": judge, "model": JUDGES[judge]["model"], "provider": JUDGES[judge]["provider"], "params": PARAMS, "git": git,
                   "cell": job["cell"], "arm": job["arm"], "kind": job["kind"], "position": job["position"], "replicate": tag,
                   "status": status, "p": p, "usage": usage, "cost_usd": cost, "latency_s": round(latency, 1), "cached": cached,
                   "prompt_sha256": hashlib.sha256(job["text"].encode()).hexdigest(), "cache_id": key}
            with open(REC, "a") as fh:
                fh.write(json.dumps(rec) + "\n")
            if status == "refusal":
                state["stop"] = "refusal"
                write_atomic(stop_file, json.dumps({"reason": "refusal", "judge": judge, "kind": job["kind"]}))
            if state["n"] <= 9 or state["n"] % 10 == 0:
                print(f"call {state['n']}: {judge} {status} in {usage.get('input', 0)} out {usage.get('output', 0)} cost ${cost:.3f} "
                      f"(est {JUDGES[judge]['est_call'][0]:.2f}-{JUDGES[judge]['est_call'][1]:.2f}); billed so far ${state['spent']:.2f}", flush=True)
        return status

    async def with_redraw(client, judge, job):
        s = await one(client, judge, job, job["replicate"])
        if s is not None and (s == "parse_failure" or s.startswith("api_error")):
            async with lock:
                state["redraws"] += 1
                if state["redraws"] > 0.10 * max(state["n"], 20):
                    state["stop"] = state["stop"] or "redraws_over_10pct"
                    return
            await one(client, judge, job, job["replicate"] + "-redraw")

    async with httpx.AsyncClient(timeout=900) as client:
        first = [(judge, job) for judge in ACTIVE for job in jobs[:2]]  # watch these before launching the rest
        await asyncio.gather(*(with_redraw(client, judge, job) for judge, job in first))
        recs = [json.loads(l) for l in REC.read_text().splitlines()] if REC.exists() else []
        for judge in ACTIVE:
            mine = [r for r in recs if r["judge"] == judge]
            if any(r["cost_usd"] > 1.5 * JUDGES[judge]["est_call"][1] for r in mine if not r["cached"]):
                state["stop"] = state["stop"] or f"first_calls_over_1.5x_estimate_{judge}"
            if not any(r["status"] == "ok" for r in mine):
                state["stop"] = state["stop"] or f"no_parsed_first_call_{judge}"
        if not state["stop"]:
            await asyncio.gather(*(with_redraw(client, judge, job) for judge in ACTIVE for job in jobs[2:]))
    print(f"done: records this run {state['n']}, billed in all ${state['spent']:.2f}, stop {state['stop']}; records -> {REC}")


if __name__ == "__main__":
    asyncio.run(main())
