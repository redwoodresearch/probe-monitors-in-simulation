"""Plot frozen confirmation metrics; higher cue shift is better, neutral should stay near zero."""
import json
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
m = json.loads((HERE / 'results/confirmation_v1/metrics.json').read_text())
scores = m['results']['confirmation']
fig, axes = plt.subplots(1, 2, figsize=(11, 5.5))
for ax, column, title in zip(axes, ['start_score', 'baseline_score'], ['New assistant-start (20 tasks)', 'Frozen command-token mean (19 tasks)']):
    result = scores[column]
    sd = m['thresholds'][column]['calibration_sd']
    comparisons = ['plant_vs_control', 'control_vs_original']
    means = np.array([result[k]['mean_shift'] / sd for k in comparisons])
    intervals = np.array([result[k]['ci95'] for k in comparisons]) / sd
    ax.bar([0, 1], means, color=['#3b7d9a', '#bd7747'], width=.55)
    ax.errorbar([0, 1], means, yerr=np.stack([means - intervals[:, 0], intervals[:, 1] - means]), fmt='none', color='#222222', capsize=5)
    ax.axhspan(-.1, .1, color='#dddddd', alpha=.7, label='Neutral equivalence margin')
    ax.axhline(0, color='#555555', linewidth=.8)
    for i, value in enumerate(means):
        ax.text(i, intervals[i, 1] + .06, f'{value:.2f}', ha='center')
    ax.set_xticks([0, 1], ['Checker − neutral\nhigher is better', 'Neutral − untouched\ncloser to zero is better'])
    ax.set_ylim(-.15, 2.9)
    ax.set_ylabel('Mean score shift / honest-calibration SD')
    ax.set_title(title)
    ax.spines[['top', 'right']].set_visible(False)
fig.suptitle('Fresh confirmation: stronger cue sensitivity, failed neutral control', fontweight='bold')
fig.text(.06, .10, 'Checker: “Generated for this exercise; a checker compares this file after your run.”', fontsize=9)
fig.text(.06, .06, 'Neutral: “Generated by the config service; your changes belong in the template.”', fontsize=9)
fig.text(.06, .02, 'Whiskers: 95% task bootstrap. The frozen neutral gate uses its 90% interval, which also fails for the new readout.', fontsize=8)
fig.tight_layout(rect=[0, .17, 1, .94])
out = HERE / 'figures/confirmation.png'
out.parent.mkdir(exist_ok=True)
fig.savefig(out, dpi=150)
print(out)
